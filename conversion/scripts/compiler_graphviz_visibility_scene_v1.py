"""Graphviz source IR plus native v5 emission, with independent source validation.

This frontend consumes a hash-bound, single Graphviz capture of a Python source.
It does not execute Python or accept a cached candidate as qualified.  Graphviz
JSON supplies authoritative endpoints; the exact original SVG supplies geometry.
The full render/font/image/editing checks remain the coordinator's responsibility.
"""
from __future__ import annotations

import copy
import hashlib
import io
import json
import math
import re
import time
import uuid
import xml.etree.ElementTree as ET
from pathlib import Path

R = Path('/backup/shaoshitong/img2code_20261029')
W = R / 'conversion'
POLICY = 'graphviz_json_explicit_nonpainting_layout_constraints_scene_v1'
LAYOUT_ATTRIBUTE = 'dataGraphvizNonpaintingConstraintsV1'
GRAPHVIZ_VERSION = '14.1.2'
DOT = W / 'runtime/graphviz/bin/dot'
ALLOWED_OPS = frozenset(('c', 'C', 'S', 'F', 'T', 't', 'E', 'e', 'P', 'p', 'L', 'b', 'B'))
DRAW_CHANNELS = ('_draw_', '_ldraw_', '_hdraw_', '_tdraw_', '_hldraw_', '_tldraw_')


def sha(blob):
    return hashlib.sha256(blob).hexdigest()


def raw(value):
    return (json.dumps(value, ensure_ascii=False, sort_keys=True, allow_nan=False) + '\n').encode()


def _read(relative, digest=None, clean=True):
    if not isinstance(relative, str) or Path(relative).is_absolute():
        raise ValueError('invalid_relative_source_locator')
    path = (R / relative).resolve(strict=True)
    floor = (R / 'clean').resolve() if clean else R.resolve()
    if not path.is_relative_to(floor):
        raise ValueError('source_payload_outside_allowed_root')
    blob = path.read_bytes()
    if digest is not None and sha(blob) != digest:
        raise ValueError('source_payload_hash_mismatch')
    return blob


def _save(path, blob):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open('xb') as stream:
        stream.write(blob)


def static_support(record):
    """No execution or outcome reads. Conservative format/feature/source predicate.

    Reads only source/capture metadata and payload identity. A true result is NOT
    source/reference fidelity, JSON layout reproducibility, or target acceptance.
    """
    reasons = []
    try:
        if record.get('source_format') != 'python':
            raise ValueError('requires_python_graphviz_capture')
        svg = _read(record['source_render_svg'], record['source_render_svg_sha256'])
        dot = _read(record['source_render_dot'])
        source = _read(record['original_source_code'], record['source_code_sha256'])
        _read(record['original_reference'], record['source_image_sha256'])
        if sha(source) != record['source_code_sha256']:
            raise ValueError('original_source_hash_mismatch')
        if not re.search(rb'Generated by graphviz version ' + GRAPHVIZ_VERSION.encode() + rb'\b', svg):
            raise ValueError('requires_pinned_graphviz_svg_version')
        root = ET.fromstring(svg)
        disallowed = {'image', 'foreignObject', 'filter', 'mask', 'clipPath', 'use', 'marker', 'textPath', 'script', 'style'}
        if any(element.tag.rsplit('}', 1)[-1] in disallowed for element in root.iter()):
            raise ValueError('unsupported_svg_feature_for_graphviz_profile')
        for element in root.iter():
            for key, value in element.attrib.items():
                if key.rsplit('}', 1)[-1] in ('href', 'src') or 'url(' in value:
                    raise ValueError('external_or_paint_server_reference_not_supported')
        text = dot.decode()
        if re.search(r'\b(?:image|shapefile)\s*=|<\s*IMG\b', text, re.I):
            raise ValueError('graphviz_external_image_not_supported')
        arrows = re.findall(r'\b(?:arrowhead|arrowtail)\s*=\s*"?([A-Za-z0-9_]+)', text)
        if any(arrow not in ('normal', 'none') for arrow in arrows):
            raise ValueError('graphviz_arrow_kind_not_supported')
        audit_bytes = _read(record['execution_audit'], clean=False)
        audit = json.loads(audit_bytes)
        if (audit.get('id'), audit.get('source_code_sha256')) != (record['id'], record['source_code_sha256']):
            raise ValueError('capture_execution_identity_mismatch')
        if not audit.get('execution', {}).get('ok') or audit.get('figures') != 1 or len(audit.get('captures', [])) != 1:
            raise ValueError('requires_one_successful_source_capture')
        capture = audit['captures'][0]
        if capture.get('engine') != 'graphviz' or capture.get('svg_sha256') != sha(svg):
            raise ValueError('capture_svg_identity_mismatch')
        captured_dot = str(Path(audit['directory']) / capture['dot'])
        if _read(captured_dot, clean=False) != dot:
            raise ValueError('capture_dot_identity_mismatch')
        if record.get('original_source_data'):
            data = _read(record['original_source_data'], record['source_data_sha256'])
            if audit.get('input_manifest', {}).get('source_data_sha256') != sha(data):
                raise ValueError('capture_source_data_identity_mismatch')
        return {'supported': True, 'group': 'python_graphviz_explicit_nonpainting_constraints_v1', 'reasons': [],
                'source_dot_sha256': sha(dot), 'source_svg_sha256': sha(svg),
                'execution_audit_sha256': sha(audit_bytes),
                'scope': 'Static supported input predicate only; no conversion or fidelity result.'}
    except (OSError, ValueError, KeyError, TypeError, ET.ParseError) as exc:
        reasons.append(str(exc))
        return {'supported': False, 'group': 'python_graphviz_explicit_nonpainting_constraints_v1', 'reasons': reasons}


def graphviz_to_scene(document):
    """Pure typed IR conversion. Reject unknown draw ops or missing graph refs."""
    if not isinstance(document, dict):
        raise ValueError('invalid_graphviz_json')
    bb = [float(value) for value in document['bb'].split(',')]
    if len(bb) != 4 or not all(math.isfinite(value) for value in bb) or bb[2] <= bb[0] or bb[3] <= bb[1]:
        raise ValueError('invalid_graphviz_layout_bbox')
    objects = document.get('objects', [])
    if not objects:
        raise ValueError('empty_graphviz_scene')
    by_id = {obj['_gvid']: obj for obj in objects}
    if len(by_id) != len(objects):
        raise ValueError('duplicate_graphviz_object_id')
    cluster_count = document.get('_subgraph_cnt', 0)
    if not isinstance(cluster_count, int) or not 0 <= cluster_count <= len(objects):
        raise ValueError('invalid_graphviz_subgraph_count')
    clusters, nodes, edges, layout_constraints = [], [], [], []

    def drawing(obj):
        result = {}
        if any(k.endswith('draw_') and k not in DRAW_CHANNELS for k in obj):
            raise ValueError('unknown_graphviz_draw_channel')
        for channel in DRAW_CHANNELS:
            if channel not in obj:
                continue
            ops = obj[channel]
            if not isinstance(ops, list):
                raise ValueError('invalid_graphviz_draw_channel')
            for op in ops:
                if op.get('op') not in ALLOWED_OPS:
                    raise ValueError('unsupported_graphviz_draw_op:' + str(op.get('op')))
                if op.get('grad', 'none') != 'none':
                    raise ValueError('unsupported_graphviz_gradient')
                if op.get('op') == 'S' and not re.fullmatch(r'(?:solid|dashed|dotted|bold|filled|invis|setlinewidth\([\d.]+\))', op['style']):
                    raise ValueError('unsupported_graphviz_paint_style')
                if op.get('op') == 'T' and not isinstance(op.get('text'), str):
                    raise ValueError('invalid_graphviz_editable_text')
            result[channel] = copy.deepcopy(ops)
        return result

    background = drawing(document)
    for index, obj in enumerate(objects):
        entry = {'source_id': obj['_gvid'], 'name': obj['name'], 'drawing': drawing(obj),
                 'source_attributes': {key: value for key, value in obj.items() if not key.startswith('_')}}
        if index < cluster_count:
            if any(node not in by_id for node in obj.get('nodes', [])):
                raise ValueError('unknown_graphviz_cluster_member')
            entry.update(children=list(obj.get('nodes', [])), child_edges=list(obj.get('edges', [])))
            clusters.append(entry)
        else:
            if not obj.get('_draw_'):
                raise ValueError('invisible_or_unlaid_graphviz_node_not_supported')
            entry['cluster_memberships'] = [cluster['source_id'] for cluster in clusters if obj['_gvid'] in cluster['children']]
            nodes.append(entry)
    names = [node['name'] for node in nodes]
    if len(set(names)) != len(names):
        raise ValueError('duplicate_graphviz_node_name')
    node_ids = {node['source_id'] for node in nodes}
    edge_ids = set()
    for obj in document.get('edges', []):
        if obj['_gvid'] in edge_ids:
            raise ValueError('duplicate_graphviz_edge_id')
        edge_ids.add(obj['_gvid'])
        if obj['tail'] not in node_ids or obj['head'] not in node_ids:
            raise ValueError('unknown_graphviz_edge_endpoint')
        channels = drawing(obj)
        styles = {token.strip() for token in obj.get('style', '').split(',')}
        if 'invis' in styles:
            if any(channels.values()):
                raise ValueError('explicit_invisible_graphviz_edge_has_paint')
            layout_constraints.append({
                'kind': 'explicit_nonpainting_layout_edge',
                'source_id': obj['_gvid'], 'source_node': obj['tail'], 'target_node': obj['head'],
                'source_name': by_id[obj['tail']]['name'], 'target_name': by_id[obj['head']]['name'],
                'source_port': obj.get('tailport'), 'target_port': obj.get('headport'),
                'drawing': channels,
                'source_attributes': {key: copy.deepcopy(value) for key, value in obj.items() if not key.startswith('_')},
                'source_payload_sha256': sha(raw(obj)),
                'explicit_invis_style_and_all_source_draw_channels_empty': True,
            })
            continue
        geometry = [op for op in obj.get('_draw_', []) if op.get('op') in ('b', 'B', 'L')]
        if len(geometry) != 1:
            raise ValueError('requires_one_visible_path_per_graphviz_edge')
        edges.append({'source_id': obj['_gvid'], 'source_node': obj['tail'], 'target_node': obj['head'],
                      'source_name': by_id[obj['tail']]['name'], 'target_name': by_id[obj['head']]['name'],
                      'source_port': obj.get('tailport'), 'target_port': obj.get('headport'),
                      'drawing': drawing(obj), 'source_attributes': {key: value for key, value in obj.items() if not key.startswith('_')}})
    return {'schema': POLICY, 'coordinates': {'units': 'graphviz_points', 'y_axis': 'up', 'bbox': bb},
            'directed': document.get('directed'), 'background': background,
            'clusters': clusters, 'nodes': nodes, 'edges': edges, 'layout_constraints': layout_constraints,
            'source_edge_count': len(edge_ids), 'visible_edge_count': len(edges), 'nonpainting_edge_count': len(layout_constraints),
            'loss_diagnostics': [], 'requires_independent_source_and_target_qa': True}



def encode_layout_constraints(xml, scene):
    """Preserve source relationships on a native cell's codec-stable property.

    The upstream model codec discards unknown mxGraphModel attributes. Custom
    mxCell properties survive actual decode, editing and encoding. Root cell 0
    is nonpainting and already exists, so this creates no visual object.
    """
    root = ET.fromstring(xml)
    model = root if root.tag == 'mxGraphModel' else root.find('.//mxGraphModel')
    if model is None:
        raise ValueError('layout_constraints_native_model_missing')
    roots=[cell for cell in model.iter('mxCell') if cell.get('id')=='0']
    if len(roots)!=1:
        raise ValueError('layout_constraints_native_root_cell_missing_or_ambiguous')
    model.attrib.pop(LAYOUT_ATTRIBUTE,None)
    roots[0].set(LAYOUT_ATTRIBUTE, raw(scene['layout_constraints']).decode().strip())
    return ET.tostring(root, encoding='unicode')


def validate_layout_constraints(scene, xml):
    root = ET.fromstring(xml)
    model = root if root.tag == 'mxGraphModel' else root.find('.//mxGraphModel')
    if model is None:
        raise ValueError('native_nonpainting_layout_constraints_missing')
    roots=[cell for cell in model.iter('mxCell') if cell.get('id')=='0']
    if len(roots)!=1 or LAYOUT_ATTRIBUTE not in roots[0].attrib:
        raise ValueError('native_nonpainting_layout_constraints_missing')
    if LAYOUT_ATTRIBUTE in model.attrib:
        raise ValueError('native_nonpainting_layout_constraints_ambiguous_carriers')
    try:
        actual = json.loads(roots[0].get(LAYOUT_ATTRIBUTE))
    except (ValueError, TypeError):
        raise ValueError('native_nonpainting_layout_constraints_invalid')
    expected = scene['layout_constraints']
    if raw(actual) != raw(expected):
        raise ValueError('native_nonpainting_layout_constraints_changed')
    if scene['source_edge_count'] != len(scene['edges']) + len(expected):
        raise ValueError('source_graphviz_edge_partition_not_complete')
    visible_ids = {edge['source_id'] for edge in scene['edges']}
    nonpaint_ids = {edge['source_id'] for edge in expected}
    if visible_ids & nonpaint_ids or len(visible_ids) != len(scene['edges']) or len(nonpaint_ids) != len(expected):
        raise ValueError('source_graphviz_edge_partition_identity_changed')
    return {'ok': True, 'source_edges': scene['source_edge_count'],
            'visible_edges': len(scene['edges']), 'explicit_nonpainting_edges': len(expected),
            'all_original_source_edge_ids_and_relationships_preserved': True,
            'constraint_metadata_sha256': sha(raw(actual)),
            'target_native_codec_carrier': 'existing_nonpainting_root_mxCell_0',
            'source_reconstructed_independently': True}

def _source_scene(record, work):
    if not DOT.is_file() or not Path('/usr/bin/bwrap').is_file():
        raise RuntimeError('infrastructure_graphviz_runtime_missing')
    predicate = static_support(record)
    if not predicate['supported']:
        raise ValueError('unsupported_graphviz_source:' + json.dumps(predicate['reasons']))
    work = Path(work).resolve()
    if not work.is_relative_to(W.resolve()):
        raise ValueError('source_frontend_work_outside_conversion')
    work.mkdir(parents=True, exist_ok=True)
    dot = _read(record['source_render_dot'], predicate['source_dot_sha256'])
    _save(work/'input.dot', dot)
    from sandbox_runner import run
    extra = [(W/'runtime/graphviz', W/'runtime/graphviz')]
    env = {'LD_LIBRARY_PATH': str(W/'runtime/graphviz/lib'), 'GVBINDIR': str(W/'runtime/graphviz/lib/graphviz')}
    outputs = {}
    for kind in ('json', 'svg'):
        process = run(work, [str(DOT), '-T'+kind, '/work/input.dot'], timeout=45, extra_ro=extra, extra_env=env)
        _save(work/('graphviz_'+kind+'.stderr'), process.stderr.encode())
        if process.returncode:
            if any(message in process.stderr for message in ('error while loading shared libraries', 'bwrap: ', 'Could not load ')):
                raise RuntimeError('infrastructure_graphviz_runtime_failed:' + process.stderr[-1000:])
            raise ValueError('graphviz_source_compile_failed:' + kind + ':' + process.stderr[-1000:])
        outputs[kind] = process.stdout.encode()
    source_svg = _read(record['source_render_svg'], record['source_render_svg_sha256'])
    if outputs['svg'] != source_svg:
        raise ValueError('fresh_dot_svg_does_not_exactly_reproduce_cached_source_layout')
    scene = graphviz_to_scene(json.loads(outputs['json']))
    scene['source'] = {'id': record['id'], 'code_sha256': record['source_code_sha256'],
                       'dot_sha256': sha(dot), 'svg_sha256': sha(source_svg),
                       'json_sha256': sha(outputs['json']), 'capture_execution_audit_sha256': predicate['execution_audit_sha256'],
                       'cached_python_capture_not_reexecuted': True}
    scene['frontend'] = {'graphviz_version': GRAPHVIZ_VERSION, 'binary_sha256': sha(DOT.read_bytes()),
                         'no_relayout_of_cached_svg': True, 'fresh_svg_exact_bytes_equal': True,
                         'sandbox': 'bwrap unshare-all, fixed read-only Graphviz/fonts and owned work only'}
    _save(work/'source_scene.json', raw(scene))
    return scene


def _json_endpoint_validation(scene, dom, xml):
    """Resolve named endpoints from DOT JSON, independently of converter stats."""
    constraint_proof = validate_layout_constraints(scene, xml)
    cells = {cell.get('id'): cell for cell in ET.fromstring(xml).iter('mxCell')}
    source_nodes = {node['name']: node for node in scene['nodes']}
    by_title = {}
    for identifier, node in dom['nodes'].items():
        title = node['title']
        if title in by_title:
            raise ValueError('ambiguous_svg_graphviz_node_title')
        by_title[title] = identifier
    if set(by_title) != set(source_nodes):
        raise ValueError('graphviz_json_svg_node_identity_mismatch')
    grouped_paths = {}
    for obj in dom['objects']:
        if obj.get('edge') and obj.get('tag') == 'path' and obj['style']['fill'] == 'none':
            grouped_paths.setdefault(obj['edge']['id'], []).append(obj)
    remaining = list(scene['edges'])
    bindings = []
    for paths in grouped_paths.values():
        if len(paths) != 1:
            raise ValueError('ambiguous_svg_graphviz_edge_paths')
        path = paths[0]
        title = path['edge']['title']
        matches = []
        for edge in remaining:
            source = edge['source_name'] + (':'+edge['source_port'] if edge['source_port'] else '')
            target = edge['target_name'] + (':'+edge['target_port'] if edge['target_port'] else '')
            operator = '->' if scene['directed'] else '--'
            if title == source + operator + target:
                matches.append(edge)
        if not matches:
            raise ValueError('graphviz_json_svg_edge_identity_mismatch')
        # Parallel edges with identical endpoints share the semantic relation;
        # retain occurrence identity and verify every path, never deduplicate.
        edge = matches[0]
        remaining.remove(edge)
        native = cells.get(path['id'])
        if native is None or native.get('edge') != '1':
            raise ValueError('missing_native_graphviz_edge')
        expected = ('node_'+by_title[edge['source_name']], 'node_'+by_title[edge['target_name']])
        if (native.get('source'), native.get('target')) != expected:
            raise ValueError('native_graphviz_json_endpoint_changed')
        bindings.append({'source_edge': edge['source_id'], 'native_edge': path['id'],
                         'source': expected[0], 'target': expected[1],
                         'source_port': edge['source_port'], 'target_port': edge['target_port']})
    if remaining:
        raise ValueError('missing_svg_or_native_graphviz_edges')
    return {'nodes': len(source_nodes), 'edges': len(bindings), 'endpoint_bindings': bindings,
            'nonpainting_layout_constraints': constraint_proof}


def validate(record, xml, frontend_report=None):
    """Independent fresh source/IR/paint/native endpoint check for new QA dispatch."""
    report = {'supported': False, 'ok': False, 'profile': POLICY, 'failures': [], 'evidence': {}}
    try:
        if sha(xml.encode()) != record['code_sha256']:
            raise ValueError('candidate_xml_hash_mismatch')
        record_ir = record.get('compiler_scene_graphviz_visibility_v1')
        if not record_ir:
            raise ValueError('missing_compiler_scene_graphviz_record')
        ir_blob = _read(record_ir['scene_file'], record_ir['scene_sha256'])
        work = W/'compiler_graphviz_visibility_scene_v1/independent_checks'/record['id']/uuid.uuid4().hex
        scene = _source_scene(record, work)
        if raw(scene) != ir_blob:
            raise ValueError('source_ir_reconstruction_changed')
        report['supported'] = True
        from PIL import Image
        width, height = Image.open(io.BytesIO(_read(record['original_reference'], record['source_image_sha256']))).size
        from auto_quality_source_vector_v2 import _capture, _graphviz_coverage, _paint_coverage
        dom, _ = _capture(record, _read(record['source_render_svg'], record['source_render_svg_sha256']), width, height, 'svg')
        if dom.get('issues'):
            raise ValueError('unsupported_source_dom_features:' + json.dumps(dom['issues'])[:2000])
        endpoints = _json_endpoint_validation(scene, dom, xml)
        coverage = _graphviz_coverage(dom, xml, record.get('svg_conversion', {}))
        paint = _paint_coverage(dom, xml)
        failures = coverage['errors'] + paint['errors']
        report.update(supported=True, ok=not failures, failures=failures,
                      evidence={'source_scene_sha256': sha(raw(scene)), 'source': scene['source'],
                                'json_endpoint_validation': endpoints, 'source_coverage': coverage,
                                'native_source_paint': paint, 'independent_source_reconstruction': True,
                                'scope': 'Source identity, complete visible source coverage, geometry/paint and editable endpoints only; fonts, actual render, original-reference fidelity and move tests remain mandatory.'})
    except Exception as exc:
        report['exception_type'] = type(exc).__name__
        report['infrastructure_failure'] = isinstance(exc, (ImportError, ModuleNotFoundError)) or str(exc).startswith('infrastructure_')
        report['failures'].append({'reason': str(exc).split(':', 1)[0], 'detail': str(exc)[:3000], 'type': type(exc).__name__})
    return report


def convert(record, job, work):
    """Finite per-case conversion. Never publishes qualification or writes SQL."""
    started = time.monotonic()
    try:
        work = Path(work).resolve()
        scene = _source_scene(record, work/'source_ir')
        from compiler_graphviz_visibility_backend_v1 import repair
        attempt = repair(record, job, work/'native_backend', scene=scene)
        if not attempt.get('ok'):
            return {**attempt, 'compiler_frontend': POLICY,
                    'infrastructure_failure': attempt.get('error_type') in ('ImportError', 'ModuleNotFoundError') or str(attempt.get('error', '')).startswith('infrastructure_')}
        candidate = attempt['record']
        dest = (R/candidate['code_file']).parent
        scene_path = dest/'graphviz_source_scene.json'
        _save(scene_path, raw(scene))
        candidate['compiler_scene_graphviz_visibility_v1'] = {'policy': POLICY,
            'scene_file': str(scene_path.relative_to(R)), 'scene_sha256': sha(raw(scene)),
            'source_dot_sha256': scene['source']['dot_sha256'], 'source_svg_sha256': scene['source']['svg_sha256'],
            'graphviz_binary_sha256': scene['frontend']['binary_sha256'],
            'requires_full_quality_revalidation': True, 'model_calls': 0}
        candidate['quality_state'] = 'pending_compiler_scene_full_qa'
        _save(dest/'compiler_candidate_record.json', raw(candidate))
        check = validate(candidate, _read(candidate['code_file'], candidate['code_sha256']).decode())
        _save(work/'source_profile.json', raw(check))
        if not check['ok']:
            return {'ok': False, 'reason': 'independent_compiler_source_profile_failed', 'diagnostics': check,
                    'candidate_record_file': str((dest/'compiler_candidate_record.json').relative_to(R)), 'model_calls': 0}
        return {'ok': True, 'record': candidate, 'source_profile': check, 'compiler_frontend': POLICY,
                'model_calls': 0, 'seconds': time.monotonic()-started}
    except Exception as exc:
        return {'ok': False, 'reason': str(exc).split(':', 1)[0], 'detail': str(exc)[:4000],
                'error_type': type(exc).__name__, 'model_calls': 0, 'seconds': time.monotonic()-started,
                'infrastructure_failure': isinstance(exc, (ImportError, ModuleNotFoundError)) or str(exc).startswith('infrastructure_')}


